#!/usr/bin/env bash

KEA_EXPORTER_BIND_ADDRESS=${KEA_EXPORTER_BIND_ADDRESS:-0.0.0.0}
KEA_EXPORTER_BIND_PORT=${KEA_EXPORTER_BIND_PORT:-9500}
KEA_EXPORTER_INTERVAL_SECONDS=${KEA_EXPORTER_INTERVAL_SECONDS:-30}
KEA_EXPORTER_SOCKETS=${KEA_EXPORTER_SOCKETS:-/var/run/kea/dhcp4.sock}

exec /usr/local/bin/kea-exporter \
	--address $KEA_EXPORTER_BIND_ADDRESS \
	--port $KEA_EXPORTER_BIND_PORT \
	--interval $KEA_EXPORTER_INTERVAL_SECONDS \
	$KEA_EXPORTER_SOCKETS \
	$@
